def _normalize_iata(raw: str | None) -> str:
    if not raw:
        return ""
    t = raw.strip().upper()
    if not t or t == "NAN":
        return ""
    return t


def canonical_seat_capacity(
    *,
    type_full: str,
    iata: Optional[str] = None,
    excel_seats: Optional[float] = None,
) -> int:
    """
    Возвращает типовую макс. вместимость по IATA или полному названию.
    Если тип не распознан — при наличии правдоподобного excel_seats (1..900) использует его.
    Иначе 180 (узкофюзеляжный «по умолчанию»).
    """
    ia = _normalize_iata(iata)
    if ia and ia in IATA_MAX_SEATS:
        return IATA_MAX_SEATS[ia]

    tl = (type_full or "").strip().lower()
    if tl and tl != "nan":
        for sub, seats in _NAME_ORDERED:
            if sub in tl:
                return seats
        # Короткие коды внутри строки без пробелов
        compact = re.sub(r"[^a-z0-9а-яё]", "", tl)
        if "б7378" in compact or "b7378" in compact:
            return 189
        if "б7373" in compact or "b7373" in compact:
            return 149

    if excel_seats is not None:
        try:
            v = float(excel_seats)
        except (TypeError, ValueError):
            v = 0.0
        if 1.0 <= v <= 900.0:
            return int(round(v))

    return 180
